    def _generate_professional_input_actions(
        self,
        person_id: str,
        meaning_id: str,
        changes: list[Change],
        priorities: list[PriorityAssessment],
        significance_assessments: list[SignificanceAssessment],
        contradictions: list[Contradiction],
    ) -> list[Action]:
        """Generate PROFESSIONAL_INPUT actions - requires clinician/care team decision."""
        actions: list[Action] = []

        # High significance changes need professional review
        high_sig_changes = []
        for change in changes:
            sig_assessment = next(
                (s for s in significance_assessments if s.change_id == change.id), None
            )
            if sig_assessment and sig_assessment.significance_level in (
                SignificanceLevel.HIGH, SignificanceLevel.CRITICAL
            ):
                high_sig_changes.append((change, sig_assessment))

        if high_sig_changes:
            for change, sig_assessment in high_sig_changes:
                actions.append(self._create_action(
                    person_id=person_id,
                    meaning_id=meaning_id,
                    action_type=ActionType.PROFESSIONAL_INPUT,
                    title=f"Clinical review of {change.measurement_type} change",
                    description=f"Discuss {change.change_type} in {change.measurement_type} with prescribing/managing clinician",
                    reason=f"{sig_assessment.significance_level.value} significance change requires clinical judgment",
                    change_ids=[change.id],
                    meaning_ids=[meaning_id],
                    evidence_ids=change.evidence_ids,
                    priority_id=None,
                    confidence=0.7,
                    uncertainty="Clinical significance and appropriate response unknown",
                    attribution="SolenOS_reasoning",
                    owner=ActionOwnership.CLINICIAN,
                    temporal_scope=TemporalScope.NEXT_APPOINTMENT,
                    priority=self._significance_to_priority(sig_assessment.significance_level),
                    what=f"Professional input needed: Review {change.measurement_type} change ({change.change_type})",
                    why=f"Significance: {sig_assessment.significance_level.value}; clinical decision required",
                    based_on=f"Change: {change.id}, Significance assessment: {sig_assessment.id}",
                    who="Clinician/care team to evaluate",
                    when="Next clinical contact or sooner if urgent",
                    what_we_dont_know="Clinical interpretation and appropriate intervention",
                    what_solenos_is_not_concluding="Not making clinical recommendations",
                ))

        # Contradictions involving medication need pharmacist/clinician input
        med_contradictions = [
            ct for ct in contradictions
            if any("medication" in eid.lower() or "med" in eid.lower() for eid in ct.evidence_ids)
        ]
        if med_contradictions:
            actions.append(self._create_action(
                person_id=person_id,
                meaning_id=meaning_id,
                action_type=ActionType.PROFESSIONAL_INPUT,
                title="Medication record reconciliation with pharmacist/clinician",
                description="Resolve conflicting medication administration records",
                reason="Medication contradictions require authoritative clarification",
                change_ids=[c.id for c in changes],
                meaning_ids=[meaning_id],
                evidence_ids=[eid for ct in med_contradictions for eid in ct.evidence_ids],
                priority_id=None,
                confidence=0.8,
                uncertainty="True medication administration history unknown",
                attribution="SolenOS_reasoning",
                owner=ActionOwnership.PHARMACIST,
                temporal_scope=TemporalScope.TODAY,
                priority=ActionPriority.URGENT,
                what="Professional input: Reconcile medication administration record",
                why="Conflicting medication records could affect safety",
                based_on=f"{len(med_contradictions)} medication contradiction(s)",
                who="Pharmacist or prescribing clinician",
                when="Today",
                what_we_dont_know="Actual medication administration history",
                what_solenos_is_not_concluding="Not recommending medication changes",
            ))

        return actions

    def _generate_escalation_actions(
        self,
        person_id: str,
        meaning_id: str,
        changes: list[Change],
        priorities: list[PriorityAssessment],
        significance_assessments: list[SignificanceAssessment],
        contradictions: list[Contradiction],
    ) -> list[Action]:
        """Generate ESCALATION actions - potential urgent concern."""
        actions: list[Action] = []

        # Check for immediate priority with critical significance
        immediate_priorities = [p for p in priorities if p.priority_level == PriorityLevel.IMMEDIATE]
        critical_changes = []
        for change in changes:
            sig_assessment = next(
                (s for s in significance_assessments if s.change_id == change.id), None
            )
            if sig_assessment and sig_assessment.significance_level == SignificanceLevel.CRITICAL:
                critical_changes.append((change, sig_assessment))

        if immediate_priorities or critical_changes:
            # Conservative escalation - only if evidence supports concern
            for change, sig_assessment in critical_changes:
                # Only escalate if we have reasonable evidence confidence
                if change.evidence_ids:
                    actions.append(self._create_action(
                        person_id=person_id,
                        meaning_id=meaning_id,
                        action_type=ActionType.ESCALATION,
                        title=f"Prompt clinical review: {change.measurement_type} change",
                        description=f"Seek timely clinical evaluation of {change.change_type} in {change.measurement_type}",
                        reason=f"Critical significance change with supporting evidence warrants prompt professional review",
                        change_ids=[change.id],
                        meaning_ids=[meaning_id],
                        evidence_ids=change.evidence_ids,
                        priority_id=immediate_priorities[0].id if immediate_priorities else None,
                        confidence=0.65,  # Lower - escalation is conservative
                        uncertainty="Urgency cannot be definitively determined from available evidence",
                        attribution="SolenOS_reasoning",
                        owner=ActionOwnership.CARE_TEAM,
                        temporal_scope=TemporalScope.NOW,
                        priority=ActionPriority.IMMEDIATE,
                        safety_classification=SafetyClassification.POTENTIAL_URGENT_CONCERN,
                        safety_basis=f"Critical significance ({sig_assessment.significance_level.value}) with evidence",
                        what="Escalation: Seek prompt clinical evaluation",
                        why=f"Critical change in {change.measurement_type} ({change.change_type}) with evidence",
                        based_on=f"Change: {change.id}, Significance: {sig_assessment.significance_level.value}",
                        who="Care team / clinical contact",
                        when="Now",
                        what_we_dont_know="Whether this represents an emergency",
                        what_solenos_is_not_concluding="Not diagnosing emergency; recommending professional evaluation",
                    ))

        return actions

    def _generate_contradiction_resolution_actions(
        self,
        person_id: str,
        meaning_id: str,
        contradictions: list[Contradiction],
        evidence_list: list[Evidence],
    ) -> list[Action]:
        """Generate information-seeking actions for contradictions (ASK/CHECK)."""
        actions: list[Action] = []

        for contradiction in contradictions:
            # If contradiction involves caregiver disagreement, suggest reconciliation
            caregiver_ids = set()
            for eid in contradiction.evidence_ids:
                ev = next((e for e in evidence_list if e.id == eid), None)
                if ev and ev.uploaded_by_caregiver_id:
                    caregiver_ids.add(ev.uploaded_by_caregiver_id)

            if len(caregiver_ids) > 1:
                actions.append(self._create_action(
                    person_id=person_id,
                    meaning_id=meaning_id,
                    action_type=ActionType.ASK,
                    title=f"Clarify with caregivers: {contradiction.description}",
                    description=f"Discuss differing observations with involved caregivers to reconcile record",
                    reason=f"Multiple caregivers report conflicting information for same measurement",
                    change_ids=[],
                    meaning_ids=[meaning_id],
                    evidence_ids=contradiction.evidence_ids,
                    priority_id=None,
                    confidence=0.75,
                    uncertainty="Which observation reflects actual state",
                    attribution="SolenOS_reasoning",
                    owner=ActionOwnership.FAMILY_COORDINATOR,
                    temporal_scope=TemporalScope.TODAY,
                    priority=ActionPriority.ROUTINE,
                    what=f"Ask caregivers: Clarify {contradiction.description}",
                    why=f"Conflicting reports from {len(caregiver_ids)} caregivers",
                    based_on=f"Contradiction: {contradiction.id}, Caregivers: {list(caregiver_ids)}",
                    who="Family coordinator to facilitate",
                    when="Today",
                    what_we_dont_know="Which caregiver's observation is accurate",
                    what_solenos_is_not_concluding="Not blaming any caregiver or deciding truth",
                ))

        return actions

    def _significance_to_priority(self, significance: SignificanceLevel) -> ActionPriority:
        """Map significance level to action priority."""
        mapping = {
            SignificanceLevel.CRITICAL: ActionPriority.IMMEDIATE,
            SignificanceLevel.HIGH: ActionPriority.URGENT,
            SignificanceLevel.MODERATE: ActionPriority.ROUTINE,
            SignificanceLevel.LOW: ActionPriority.LOW,
            SignificanceLevel.NONE: ActionPriority.DEFERRED,
            SignificanceLevel.UNKNOWN: ActionPriority.MONITOR,
        }
        return mapping.get(significance, ActionPriority.ROUTINE)

