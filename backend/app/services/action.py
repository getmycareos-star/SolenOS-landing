    def _validate_action(
        self,
        action: Action,
        evidence_list: list[Evidence],
        changes: list[Change],
    ) -> bool:
        """Validate action before persistence - safety gate."""
        # Grounding: action must reference actual evidence, changes, or meaning
        if not action.evidence_ids and not action.change_ids and not action.meaning_ids:
            return False

        # Scope: no medication changes, no diagnoses, no treatment plans
        unsafe_keywords = [
            "stop taking", "start taking", "increase dose", "decrease dose",
            "double dose", "skip dose", "take another", "reduce medication",
            "diagnosis", "diagnose", "is causing", "caused by",
            "emergency", "call 911", "go to er",
        ]
        text = f"{action.title} {action.description} {action.reason}".lower()
        if any(kw in text for kw in unsafe_keywords):
            return False

        # Safety: escalation must have evidence
        if action.safety_classification in (
            SafetyClassification.PROMPT_PROFESSIONAL_REVIEW,
            SafetyClassification.POTENTIAL_URGENT_CONCERN
        ) and not action.evidence_ids:
            return False

        # Attribution: must be clear
        if not action.attribution:
            return False

        # Temporal validity: action must have temporal scope
        if not action.temporal_scope:
            return False

        # Clinical authority: caregiver actions must not substitute clinical judgment
        if action.owner == ActionOwnership.CAREGIVER and action.action_type in (
            ActionType.PROFESSIONAL_INPUT, ActionType.ESCALATION
        ):
            # This is ok - caregiver can SEEK professional input
            pass

        return True

    def _build_reasoning_summary(
        self,
        changes: list[Change],
        priorities: list[PriorityAssessment],
        significance_assessments: list[SignificanceAssessment],
        contradictions: list[Contradiction],
        information_gaps: list[InformationGap],
    ) -> str:
        """Build human-readable reasoning chain summary."""
        parts = []
        if changes:
            parts.append(f"{len(changes)} change(s) detected")
        if priorities:
            parts.append(f"{len(priorities)} priority assessment(s)")
        if significance_assessments:
            parts.append(f"{len(significance_assessments)} significance assessment(s)")
        if contradictions:
            parts.append(f"{len(contradictions)} contradiction(s)")
        if information_gaps:
            parts.append(f"{len(information_gaps)} information gap(s)")
        return "; ".join(parts) if parts else "No structured reasoning input"

    def update_action_status(
        self,
        action: Action,
        new_status: ActionStatus,
        triggered_by: str = "caregiver",
        reason: str | None = None,
    ) -> ActionHistoryEntry:
        """Update action status and create history entry."""
        previous_state = {
            "status": action.status,
            "acknowledged_at": action.acknowledged_at,
            "completed_at": action.completed_at,
        }

        action.status = new_status
        now = datetime.utcnow()

        if new_status == ActionStatus.ACKNOWLEDGED:
            action.acknowledged_at = now
        elif new_status == ActionStatus.COMPLETED:
            action.completed_at = now
        elif new_status == ActionStatus.SUPERSEDED:
            action.superseded_at = now
            action.superseded_reason = reason

        new_state = {
            "status": action.status,
            "acknowledged_at": action.acknowledged_at,
            "completed_at": action.completed_at,
        }

        history_entry = ActionHistoryEntry(
            id=f"ah_{datetime.utcnow().strftime('%Y%m%d%H%M%S%f')}",
            action_id=action.id,
            person_id=action.person_id,
            change_type=new_status.value,
            previous_state=previous_state,
            new_state=new_state,
            reason=reason,
            triggered_by=triggered_by,
        )

        return history_entry

    def supersede_action(
        self,
        action: Action,
        superseded_by_id: str,
        reason: str,
    ) -> ActionHistoryEntry:
        """Mark action as superseded by a new action."""
        previous_state = {
            "status": action.status,
            "superseded_by": action.superseded_by,
        }

        action.status = ActionStatus.SUPERSEDED
        action.superseded_by = superseded_by_id
        action.superseded_at = datetime.utcnow()
        action.superseded_reason = reason

        new_state = {
            "status": action.status,
            "superseded_by": action.superseded_by,
            "superseded_at": action.superseded_at,
        }

        return ActionHistoryEntry(
            id=f"ah_{datetime.utcnow().strftime('%Y%m%d%H%M%S%f')}",
            action_id=action.id,
            person_id=action.person_id,
            change_type="superseded",
            previous_state=previous_state,
            new_state=new_state,
            reason=reason,
            triggered_by="system",
        )