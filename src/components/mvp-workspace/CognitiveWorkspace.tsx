/** Read or mint interaction session — never the durable care key (Locked A). */
function interactionSessionId(forceNew = false): string {
  if (typeof window === "undefined") return ensureClientInteractionSessionId(null, { forceNew });
  const next = ensureClientInteractionSessionId(
    window.localStorage.getItem(CARE_SESSION_STORAGE_KEY),
    { forceNew },
  );
  window.localStorage.setItem(CARE_SESSION_STORAGE_KEY, next);
  return next;
}

type SubmitPhase = "idle" | "acknowledged" | "processing" | "done";

/** Detect interaction-only input for routing; response wording is generated by Qwen. */
function isLcrOrientationOnly(text: string): boolean {
  const normalized = text
    .trim()
    .toLocaleLowerCase()
    .replace(/[.!?,;:]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
  const greeting = /^(hi|hello|hey|hiya|howdy|yo|good morning|good afternoon|good evening|good night|how are you|how are you doing|how are you today|how are you doing today|how's it going|hows it going|what's up|whats up|sup|thanks|thank you|thank you so much|i appreciate your help|appreciate it|bye|goodbye|see you)$/i;
  const frustration = /^(this is useless|this thing is useless|you are stupid|you're stupid|you are dumb|you're dumb|you are useless|you're useless|you are incompetent|you're incompetent|you suck|you don't understand anything|you never get anything right|you got this wrong|that is wrong|that's wrong|fuck you|f\*ck you|idiot|stupid|useless)$/i;
  return greeting.test(normalized) || frustration.test(normalized);
}

/** Build caregiver-facing + LCR display text from typed note and/or ready documents. */

function buildSharedDisplayText(text: string, docs: AttachedDocument[]): string {
  const parts: string[] = [];
  const trimmed = text.trim();
  if (trimmed) parts.push(trimmed);
  for (const d of docs) {
    if (d.status !== "ready" || !d.extractedText.trim()) continue;
    parts.push(`[Document: ${d.name}]\n${d.extractedText.trim()}`);
  }
  return parts.join("\n\n");
}

